//===============  RUNTIME CONFIG READ / WRITE ===========
//
// Runtime configuration contains the user-selected operating mode and any
// tunable parameters associated with that mode.
//
// For example, this might include which haptic model is active and the
// constants/gains used by that model.
//
// This config may be updated by setup/telemetry code and read by the
// control task each loop (or each model update).

